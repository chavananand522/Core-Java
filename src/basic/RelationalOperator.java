
package basic;

public class RelationalOperator {

	public static void main(String[] args) {
		
		int a= 20;
		int b= 69;
		
		System.out.println(a>b);
		System.out.println(a<b);
		System.out.println(a<=b);
		System.out.println(a>=b);
		System.out.println(a==b);
		System.out.println(a!=b);
		
		
	}

}
