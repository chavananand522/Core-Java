package basic;

public class AssignmentOperator {

	public static void main(String[] args) {

		int marks = 89;
		int price =20000;
		int petrol = 900;
		int rent = 2000;
		int percentage = 40;

		marks += 10;
		price -= 30;
		petrol *= 7;
		rent /= 20;
		percentage %= 5;

		System.out.println(marks);
		System.out.println(price);
		System.out.println(petrol);
		System.out.println(rent);
		System.out.println(percentage);

	}

}
